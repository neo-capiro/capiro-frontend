import { expect, it } from "vitest";
import {
  bindGenerationProposal,
  bindGenerationList,
  bindGenerationDecision,
  generationRecoveryContract,
} from "../src/features/modules/workspace/prospects/generation";
import {
  generationBody,
  generationProposal,
  generationList,
  generationDecisionFixture,
  scope,
  draft,
} from "./prospect-generation-fixture";
import { workspaceProspectGenerationOperations } from "../src/shared/capiro/operations/workspace-prospect-generation";
import { ordinarySaveConflictCode } from "../src/shared/capiro/workspace-ordinary-save-errors";
import { serviceErrorResponse } from "../src/shared/capiro/gateway-errors";

it("binds the exact source selection, writing brief, actor and generated bytes", async () => {
  const input = await generationBody(),
    proposal = await generationProposal(input);
  expect(
    await bindGenerationProposal(
      proposal,
      scope,
      input.requestId,
      input,
      draft.ownerId,
    ),
  ).toEqual(proposal);
  expect(
    bindGenerationList(generationList([proposal]), scope).proposals[0]!.output,
  ).toBeNull();
  for (const changed of [
    { ...proposal, writingBrief: "Changed" },
    { ...proposal, createdById: "another-user" },
    { ...proposal, selectedSections: ["Other"] },
    { ...proposal, outputHash: "f".repeat(64) },
    {
      ...proposal,
      source: { ...proposal.source, sourceSnapshotHash: "f".repeat(64) },
    },
    { ...proposal, prospectId: proposal.proposalId },
    { ...proposal, output: null },
  ])
    await expect(
      bindGenerationProposal(
        changed,
        scope,
        input.requestId,
        input,
        draft.ownerId,
      ),
    ).rejects.toThrow();
});
it("confirms acceptance only against the exact immutable saved content and decision", async () => {
  const proposal = await generationProposal();
  const intent = {
    kind: "decision" as const,
    proposalId: proposal.proposalId,
    body: {
      requestId: crypto.randomUUID(),
      decision: "accept" as const,
      expectedStateHash: proposal.baseStateHash,
      outputHash: proposal.outputHash!,
    },
  };
  const { result, saved } = await generationDecisionFixture(
    proposal,
    intent.body,
  );
  expect(
    (await bindGenerationDecision(result, scope, draft.ownerId, intent, saved))
      .proposal.status,
  ).toBe("accepted");
  await expect(
    bindGenerationDecision(result, scope, "another-user", intent, saved),
  ).rejects.toThrow();
  await expect(
    bindGenerationDecision(result, scope, draft.ownerId, intent, {
      ...saved,
      snapshot: { ...saved.snapshot, docTitle: "Changed" },
    }),
  ).rejects.toThrow();
  await expect(
    bindGenerationDecision(
      { ...result, save: null },
      scope,
      draft.ownerId,
      intent,
      saved,
    ),
  ).rejects.toThrow();
});
it("keeps original recovery intent immutable and rejects extra authority fields", async () => {
  const intent = { kind: "generate" as const, body: await generationBody() };
  expect(() =>
    generationRecoveryContract.validateUpdate(intent, {
      ...intent,
      body: { ...intent.body, writingBrief: "Changed" },
    }),
  ).toThrow();
  const op =
    workspaceProspectGenerationOperations[
      "workspace.prospect.generation.create"
    ];
  expect(
    op.request.safeParse({
      params: { draftId: scope.id },
      body: { ...intent.body, actorId: draft.ownerId },
    }).success,
  ).toBe(false);
  expect(
    op.request.safeParse({
      params: { draftId: scope.id },
      body: { ...intent.body, writingBrief: "🧪".repeat(1001) },
    }).success,
  ).toBe(false);
});
it("only forwards known conflict codes on the exact generation routes", () => {
  const operation =
    workspaceProspectGenerationOperations[
      "workspace.prospect.generation.decide"
    ];
  expect(
    ordinarySaveConflictCode(operation, 409, {
      code: "WORKSPACE_SAVE_STATE_CONFLICT",
    }),
  ).toBe("WORKSPACE_SAVE_STATE_CONFLICT");
  expect(
    ordinarySaveConflictCode(operation, 409, { code: "OTHER_ERROR" }),
  ).toBeUndefined();
  expect(
    ordinarySaveConflictCode({ ...operation, path: "/unrelated" }, 409, {
      code: "WORKSPACE_SAVE_STATE_CONFLICT",
    }),
  ).toBeUndefined();
});
it("preserves a stale acceptance refusal through the actual service gateway", async () => {
  const operation =
    workspaceProspectGenerationOperations[
      "workspace.prospect.generation.decide"
    ];
  const response = await serviceErrorResponse(
    new Response(JSON.stringify({ code: "WORKSPACE_SAVE_STATE_CONFLICT" }), {
      status: 409,
    }),
    operation,
    new AbortController().signal,
    false,
  );
  expect(await response.json()).toMatchObject({
    code: "WORKSPACE_SAVE_STATE_CONFLICT",
  });
});

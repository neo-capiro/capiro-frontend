import { expect, it } from "vitest";
import { officeCreations } from "../src/features/modules/workspace/WorkspaceScreen";

it("offers Word, Excel and PowerPoint; only the deployment's document family opens the Files editor", () => {
  expect(officeCreations("create_word")).toEqual([
    { kind: "word", label: "Word document", href: "/meri/files" },
    {
      kind: "excel",
      label: "Excel workbook (ask Meri in chat)",
      href: "/meri",
    },
    {
      kind: "powerpoint",
      label: "PowerPoint deck (ask Meri in chat)",
      href: "/meri",
    },
  ]);
  expect(officeCreations("create_excel").map((e) => [e.kind, e.href])).toEqual([
    ["word", "/meri"],
    ["excel", "/meri/files"],
    ["powerpoint", "/meri"],
  ]);
  // No document family bound: every kind is generated by Meri in chat, and the entry says so.
  expect(officeCreations(null).every((e) => e.href === "/meri")).toBe(true);
  expect(officeCreations(null).every((e) => e.label.endsWith("(ask Meri in chat)"))).toBe(true);
});

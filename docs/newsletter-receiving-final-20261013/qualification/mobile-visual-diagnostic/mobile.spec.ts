import { test, expect } from '/workspace/capiro-newsletter-port/node_modules/@playwright/test/index.mjs';
import { onlyLocalRequests, operationFixtures } from '/workspace/capiro-newsletter-port/apps/web/test/browser/fixtures';
import { moduleRouteFixtures } from '/workspace/capiro-newsletter-port/apps/web/test/browser/module-route-fixtures';
test('mobile rich editor paints editable controls, structure and preview when scrolled after viewport replacement',async({page},info)=>{
 await onlyLocalRequests(page); await operationFixtures(page,moduleRouteFixtures);
 const errors:string[]=[],writes:string[]=[],remote:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(new URL(r.url()).hostname!=='127.0.0.1')remote.push(r.url());if(r.url().includes('/api/capiro/')&&r.method()!=='GET')writes.push(r.url());});
 await page.goto('/modules/workspace?view=rich-newsletter');
 await page.getByRole('button',{name:/^Heading · This week in policy/}).click();
 await page.getByRole('textbox',{name:'Block rich text'}).fill('Synthetic local heading');
 await expect(page.frameLocator('iframe[title="Rich newsletter preview"]').getByRole('heading',{name:'Synthetic local heading'})).toBeVisible();
 await page.getByRole('button',{name:'Mobile preview'}).click();
 await page.getByRole('button',{name:'Plain text',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))));
 await page.screenshot({path:info.outputPath('mobile-full-after-paint.png'),fullPage:true});
 const name=page.getByRole('textbox',{name:'Newsletter name',exact:true});
 await name.scrollIntoViewIfNeeded(); await name.fill('Mobile synthetic newsletter');
 await expect(name).toHaveValue('Mobile synthetic newsletter');
 await page.screenshot({path:info.outputPath('mobile-fields-viewport.png')});
 const heading=page.getByRole('button',{name:'Heading · Synthetic local heading',exact:true});
 await heading.scrollIntoViewIfNeeded(); await expect(heading).toBeVisible();
 await page.screenshot({path:info.outputPath('mobile-structure-viewport.png')});
 const plain=page.getByLabel('Newsletter plain text');
 await plain.scrollIntoViewIfNeeded(); await expect(plain).toContainText('Synthetic local heading');
 await page.screenshot({path:info.outputPath('mobile-plain-preview-viewport.png')});
 await page.getByRole('button',{name:'Rich preview',exact:true}).click();
 const iframe=page.locator('iframe[title="Rich newsletter preview"]');await iframe.scrollIntoViewIfNeeded();
 await expect(page.frameLocator('iframe[title="Rich newsletter preview"]').getByRole('heading',{name:'Synthetic local heading'})).toBeVisible();
 await page.screenshot({path:info.outputPath('mobile-html-preview-viewport.png')});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);expect(writes).toEqual([]);expect(remote).toEqual([]);
 await info.attach('layout',{body:JSON.stringify(await page.evaluate(()=>({viewport:{width:innerWidth,height:innerHeight},scrollHeight:document.documentElement.scrollHeight,scrollWidth:document.documentElement.scrollWidth}))),contentType:'application/json'});
});

import {readFileSync,writeFileSync,mkdirSync,symlinkSync,existsSync} from 'node:fs';
import {resolve,dirname,join,relative,isAbsolute} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync,spawnSync} from 'node:child_process';

const [checkoutArg,outputArg]=process.argv.slice(2);
if(!checkoutArg||!outputArg)throw new Error('Usage: node run-client-clear.mjs CHECKOUT FRESH_EXTERNAL_OUTPUT');
const checkout=resolve(checkoutArg),out=resolve(outputArg);
const relation=relative(checkout,out);
if(!relation||(!relation.startsWith('..')&&!isAbsolute(relation)))throw new Error('Output must be outside the source checkout.');
if(existsSync(out))throw new Error('Use a fresh output directory to preserve existing evidence.');
const canonical=readFileSync(join(dirname(fileURLToPath(import.meta.url)),'client-clear.canonical.spec.ts'),'utf8');
const expected='825c56e51ffd385ea9be30255a0f1784505740d6713b8925477f8883d2a4e5df';
const sha=value=>createHash('sha256').update(value).digest('hex');
if(sha(canonical)!==expected)throw new Error('Canonical control bytes changed.');
const original="'/workspace/review-pr13/r1/source/apps/web/tests/browser/fixtures'";
if(canonical.split(original).length!==2)throw new Error('Expected exactly one fixture import substitution.');
const replacement=JSON.stringify(join(checkout,'apps/web/tests/browser/fixtures'));
const executed=canonical.replace(original,replacement);
mkdirSync(out,{recursive:true});
writeFileSync(join(out,'package.json'),'{"type":"module"}\n');
symlinkSync(join(checkout,'node_modules'),join(out,'node_modules'),'dir');
writeFileSync(join(out,'control.spec.ts'),executed);
const git=(...args)=>execFileSync('git',args,{cwd:checkout,encoding:'utf8'}).trim();
const source={head:git('rev-parse','HEAD'),tree:git('rev-parse','HEAD^{tree}'),applicationTree:git('rev-parse','HEAD:apps/web/src'),status:git('status','--short'),canonicalSha256:expected,executedSha256:sha(executed),substitution:{original,replacement}};
writeFileSync(join(out,'source.json'),JSON.stringify(source,null,2)+'\n');
const config=`import {defineConfig} from '@playwright/test';\nimport original from ${JSON.stringify(join(checkout,'apps/web/playwright.config'))};\nexport default defineConfig({...original,testDir:${JSON.stringify(out)},testMatch:'control.spec.ts',outputDir:${JSON.stringify(join(out,'artifacts'))},reporter:[['list'],['json',{outputFile:${JSON.stringify(join(out,'results.json'))}}]],webServer:{...original.webServer,command:${JSON.stringify(`"${process.execPath}" ${join(checkout,'apps/web/tests/browser/server.mjs')}`)}}});\n`;
writeFileSync(join(out,'review.playwright.ts'),config);
const result=spawnSync(process.execPath,[join(checkout,'node_modules/@playwright/test/cli.js'),'test','--config',join(out,'review.playwright.ts')],{cwd:join(checkout,'apps/web'),env:{...process.env,PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH||'/usr/bin/chromium'},encoding:'utf8',maxBuffer:8*1024*1024});
const log=(result.stdout??'')+(result.stderr??'');
writeFileSync(join(out,'run.txt'),log);
const finish={head:git('rev-parse','HEAD'),tree:git('rev-parse','HEAD^{tree}'),status:git('status','--short')};
const sourceChanged=finish.head!==source.head||finish.tree!==source.tree||finish.status!==source.status;
writeFileSync(join(out,'exit.json'),JSON.stringify({exitCode:result.status,signal:result.signal,error:result.error?.message,finish,sourceChanged},null,2)+'\n');
process.stdout.write(log);process.exitCode=sourceChanged?1:(result.status??1);
